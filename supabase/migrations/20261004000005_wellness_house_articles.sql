**1 · The Problem: Treating the Dip as a Fault to Be Fixed Right Now**

In a culture that measures a person by an ever rising curve, a natural drop in energy has become something to be ashamed of and hunted down:

• You wake heavy for no reason, and instead of moving through the day quietly, you begin diagnosing yourself: am I depressed? have I lost my drive? And you spend the day analyzing the day instead of living it.

