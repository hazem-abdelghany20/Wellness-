**2 · The Cause: Three Beliefs That Put Your Mood in Charge**

Hardly anyone decides to make his mood his master. It happens through three beliefs that slip in without a decision:

1. The high state is the normal state. You have seen people only in their best hours, because nobody films their heavy ones, so you built a picture of a human being who never dips, and every dip of yours became a deviation from normal rather than a part of it.

2. Feelings are reports about reality. You believe today's feeling is telling you the truth about your work, your relationships and your future. Usually it is telling you only about your sleep, your food, and the week's pressure. And when you treat a passing feeling as a report, you make decisions on it that should never be made on a day like this.

3. The cure is to raise the state immediately. So you reach for whatever lifts it fastest, and the fastest is always the shortest lived, so you rise for an hour and fall for two, and your day becomes a chase instead of a day.

And there is a deeper truth beneath the three: the dip does a job the surge cannot do, and the surge does a job the dip cannot. The surge gives you momentum to build. The dip gives you what nothing else will: it shows you what you built on enthusiasm alone, because that collapses, and what you built on something firmer, because that holds.

**3 · The Simple Solution: Do Not Let Your Commitment Be the Child of Your Mood**

The way out does not begin with trying to abolish heavy days, since they cannot be abolished. It begins with reclassifying where you stand: you are not your state. The state rises and falls by its nature, and you are the constant between them. What is required is not to feel a particular way, but to do what you agreed with yourself to do, at a dose that fits the day.

This reverses the meaning of both kinds of day. The high day becomes an opportunity to build rather than a certificate that you are well. The heavy day becomes a test of what you built rather than a verdict on you.

When this classification settles:

• The heavy day passes as a day, not a catastrophe, so its length shrinks from days to hours.

• You stop making big decisions in your worst hours and your best ones alike, and both are poor times to decide.

• Your output steadies, because it is no longer hanging on a feeling whose schedule you do not control.

The practical rule: do not decide on a high day or a heavy one, do not measure your life by one morning's mood, and on both days do the smallest thing you agreed to do.

